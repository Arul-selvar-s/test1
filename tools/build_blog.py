#!/usr/bin/env python3
"""
Elysian Dental Lounge - blog builder
====================================

WHAT THIS DOES (in plain English)
  Reads the articles written in the admin editor (the files in content/blog/)
  and automatically creates:
    - one web page for every published article      (blog-post-<name>.html)
    - the list the blog page and homepage read from   (posts.json)
    - sitemap.xml and robots.txt for Google          (use the website address automatically)
    - admin/status.html, a page that tells the admin, in plain English,
      which articles are live, scheduled, drafts, or have a problem and why.

  It runs by itself on GitHub (see .github/workflows/build-blog.yml) every time
  an article is saved, and once every night so scheduled articles go live.
  Nobody has to run it by hand.

THE WEBSITE ADDRESS
  Nothing here is tied to one address. The address is found automatically:
    1. the SITE_URL setting, if one is given
    2. otherwise the file named CNAME (GitHub creates it when a custom domain
       is connected), so moving to a new domain needs no change at all
    3. otherwise the free github.io address of the repository.

To run it yourself (only needed for testing):   python3 tools/build_blog.py
Needs:  pip install markdown pyyaml
"""
import html
import json
import os
import re
import subprocess
import sys
from datetime import date, datetime, timedelta, timezone
from pathlib import Path
from urllib.parse import quote

try:
    import markdown
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("The blog builder needs two helper packages. Install them with:  pip install markdown pyyaml")

ROOT = Path(os.environ.get("BLOG_ROOT") or Path(__file__).resolve().parent.parent)
CONTENT = ROOT / "content" / "blog"
TEMPLATE = Path(__file__).resolve().parent / "post-template.html"
MARKER = "<!-- generated-by: tools/build_blog.py (do not edit this file by hand; edit the article in the admin editor) -->"
IST = timezone(timedelta(hours=5, minutes=30))  # the clinic's time zone
TODAY = datetime.now(IST).date()

# Articles that existed before the editor was added keep their old web address,
# so links that were already shared keep working.
LEGACY_FILENAMES = {
    "clearalign-vs-traditional-braces": "blog-post-2.html",
}

CATEGORIES = ["Oral Health", "Cosmetic Dentistry", "Orthodontics", "Dental Implants",
              "Kids Dentistry", "Daily Tips", "Patient Stories", "Clinic News"]
CLINIC = "Elysian Dental Lounge"
BIG_IMAGE_BYTES = 600 * 1024


# --------------------------------------------------------------------------- helpers
def esc(s):
    return html.escape(str(s), quote=True)


def write_if_changed(path, text):
    """Write a file only when its content really changed (keeps the history quiet)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    data = text.encode("utf-8")
    if path.exists() and path.read_bytes() == data:
        return False
    path.write_bytes(data)
    return True


def find_site_url():
    env = os.environ.get("SITE_URL", "").strip().rstrip("/")
    if env:
        return env
    cname = ROOT / "CNAME"
    if cname.exists():
        lines = [l.strip() for l in cname.read_text(encoding="utf-8").splitlines() if l.strip()]
        if lines:
            return "https://" + lines[0].replace("https://", "").replace("http://", "").rstrip("/")
    repo = os.environ.get("GITHUB_REPOSITORY", "")
    if "/" not in repo:
        try:
            remote = subprocess.check_output(["git", "-C", str(ROOT), "config", "--get", "remote.origin.url"],
                                             text=True, stderr=subprocess.DEVNULL).strip()
            m = re.search(r"github\.com[:/]+([^/]+)/([^/]+?)(?:\.git)?$", remote)
            if m:
                repo = m.group(1) + "/" + m.group(2)
        except Exception:
            pass
    if "/" in repo:
        owner, name = repo.split("/", 1)
        host = owner.lower() + ".github.io"
        return "https://" + host if name.lower() == host else "https://%s/%s" % (host, name)
    return ""


def parse_date(value):
    """Accepts 2026-04-08, 2026-04-08T10:30:00Z, or a real date. Returns a date in clinic time."""
    if isinstance(value, datetime):
        if value.tzinfo:
            value = value.astimezone(IST)
        return value.date()
    if isinstance(value, date):
        return value
    text = str(value or "").strip()
    if not text:
        return None
    if re.fullmatch(r"\d{4}-\d{2}-\d{2}", text):
        return date.fromisoformat(text)
    try:
        dt = datetime.fromisoformat(text.replace("Z", "+00:00"))
        if dt.tzinfo:
            dt = dt.astimezone(IST)
        return dt.date()
    except ValueError:
        return None


def truthy(v):
    if isinstance(v, bool):
        return v
    return str(v).strip().lower() in ("true", "yes", "1", "on")


def split_front_matter(raw):
    raw = raw.replace("\r\n", "\n").lstrip("﻿")
    m = re.match(r"---\n(.*?)\n---\n?(.*)\Z", raw, re.S)
    if not m:
        return None, raw
    return m.group(1), m.group(2)


CLEAN_TAGS = re.compile(r"<\s*(script|iframe|object|embed|style|form)\b.*?<\s*/\s*\1\s*>|<\s*(script|iframe|object|embed|style|form)\b[^>]*>",
                        re.I | re.S)
EVENT_ATTRS = re.compile(r"\s+on[a-z]+\s*=\s*(\"[^\"]*\"|'[^']*'|[^\s>]+)", re.I)


def render_body(md_text):
    body = markdown.markdown(md_text, extensions=["extra", "sane_lists"], output_format="html5")
    body = CLEAN_TAGS.sub("", body)           # safety: no scripts / embeds from article text
    body = EVENT_ATTRS.sub("", body)
    body = re.sub(r"javascript\s*:", "", body, flags=re.I)
    body = body.replace("<h1", "<h2").replace("</h1>", "</h2>")   # the page title is already the main heading
    # pictures added inside the article: make the path work from any address, load lazily
    body = re.sub(r'(src|href)="/(images/)', r'\1="\2', body)
    body = re.sub(r"<img (?![^>]*loading=)", '<img loading="lazy" ', body)
    return body


def clean_image_path(p):
    """Editor stores /images/blog/x.webp. Make it relative so it works on github.io/<repo>/ and on a custom domain."""
    p = str(p or "").strip()
    if not p or re.match(r"^(https?:)?//", p) or p.startswith("data:"):
        return p
    return p.lstrip("/")


def absolute(site_url, path):
    if not path or re.match(r"^(https?:)?//", path):
        return path
    return (site_url + "/" + path.lstrip("/")) if site_url else ""


# --------------------------------------------------------------------------- load articles
def load_articles(problems):
    posts = []
    if not CONTENT.exists():
        return posts
    used_files = {}
    for f in sorted(CONTENT.glob("*.md")):
        name = f.name
        slug = f.stem

        def problem(field, why, fix):
            problems.append({"article": name, "field": field, "why": why, "fix": fix})

        fm_text, body = split_front_matter(f.read_text(encoding="utf-8"))
        if fm_text is None:
            problem("whole file", "The top part of the file (the details block between two '---' lines) is missing.",
                    "Open this article in the admin editor and save it again, or ask your web helper to restore it.")
            continue
        try:
            fm = yaml.safe_load(fm_text) or {}
            if not isinstance(fm, dict):
                raise ValueError("not a list of fields")
        except Exception as e:  # noqa: BLE001
            problem("whole file", "The details at the top of the article could not be read (%s)." % str(e).splitlines()[0],
                    "Open the article in the admin editor and save it again. If the editor cannot open it, a symbol such as a colon or quote in the title may need fixing.")
            continue

        title = str(fm.get("title") or "").strip()
        if len(title) < 3:
            problem("Title", "The article has no title.", "Open it in the editor and type a title.")
            continue

        d = parse_date(fm.get("date"))
        if not d:
            problem("Date", "The date is missing or not a real date (found: %r)." % (fm.get("date"),),
                    "Open the article in the editor and pick the date again.")
            continue

        text_body = (body or "").strip()
        if len(text_body) < 20:
            problem("Article text", "The article has no text (or almost none).", "Open it in the editor and write the article.")
            continue

        category = str(fm.get("category") or "").strip()
        if not category:
            problem("Category", "No category was chosen.", "Open the article and choose a category.")
            continue

        excerpt = re.sub(r"\s+", " ", str(fm.get("excerpt") or "")).strip()
        if not excerpt:
            problem("Short excerpt", "The short description shown on the blog list is empty.", "Open the article and write one or two sentences.")
            continue

        # draft / published switches (old files used 'draft')
        if "published" in fm:
            published = truthy(fm.get("published"))
        elif "draft" in fm:
            published = not truthy(fm.get("draft"))
        else:
            published = False
        status = "draft"
        if published:
            status = "live" if d <= TODAY else "scheduled"

        image = clean_image_path(fm.get("image"))
        if image and not re.match(r"^(https?:)?//", image):
            img_file = ROOT / image
            if not img_file.exists():
                problems.append({"article": name, "field": "Cover photo", "level": "note",
                                 "why": "The photo '%s' is not in the website files, so the article is shown without its cover photo." % image,
                                 "fix": "Open the article, choose the cover photo again (upload it), and save."})
                image = ""
            elif img_file.stat().st_size > BIG_IMAGE_BYTES:
                problems.append({"article": name, "field": "Cover photo", "level": "note",
                                 "why": "The cover photo is large (%d KB), which makes the page slower on mobile data." % (img_file.stat().st_size // 1024),
                                 "fix": "Upload a smaller version of the photo (under about 500 KB)."})

        if len(excerpt) > 180:
            problems.append({"article": name, "field": "Short excerpt", "level": "note",
                             "why": "The short excerpt is %d characters; over 180 may be cut off in search results." % len(excerpt),
                             "fix": "Shorten it to one or two sentences."})
        if category not in CATEGORIES:
            problems.append({"article": name, "field": "Category", "level": "note",
                             "why": "'%s' is not one of the usual categories, so it will not appear under a category button on the blog page." % category,
                             "fix": "Choose one of the categories offered in the editor."})

        filename = LEGACY_FILENAMES.get(slug, "blog-post-%s.html" % slug)
        if filename in used_files:
            problem("Title", "Another article already uses the same web address (%s)." % filename, "Change the title of one of them slightly.")
            continue
        used_files[filename] = name

        posts.append({
            "slug": slug, "source": name, "filename": filename, "title": title, "date": d, "category": category,
            "excerpt": excerpt, "image": image, "alt": str(fm.get("image_alt") or title).strip(),
            "author": str(fm.get("author") or "Dr. Yokesh Kumar R").strip(), "status": status, "body_md": text_body,
        })
    return posts


# --------------------------------------------------------------------------- output
def date_display(d):
    return "%s %d, %d" % (d.strftime("%B"), d.day, d.year)


def build_pages(live, site_url, template):
    wrote = 0
    cats = {}
    for p in live:
        cats[p["category"]] = cats.get(p["category"], 0) + 1
    side = "\n".join('        <a href="blog.html?cat=%s">%s <span class="cat-count">%d</span></a>' % (quote(c), esc(c), n)
                     for c, n in sorted(cats.items(), key=lambda kv: (-kv[1], kv[0]))) or '        <a href="blog.html">All articles</a>'

    for i, p in enumerate(live):
        newer = live[i - 1] if i > 0 else None
        older = live[i + 1] if i + 1 < len(live) else None
        nav = "" if not (older or newer) else '<div class="post-nav">%s%s</div>' % (
            ('<a class="post-nav-btn" href="%s">← %s</a>' % (esc(older["filename"]), esc(older["title"]))) if older else "<span></span>",
            ('<a class="post-nav-btn" href="%s">%s →</a>' % (esc(newer["filename"]), esc(newer["title"]))) if newer else "<span></span>")

        page_url = (site_url + "/" + p["filename"]) if site_url else ""
        og_img = absolute(site_url, p["image"])
        meta = ['<meta name="description" content="%s"/>' % esc(p["excerpt"])]
        if page_url:
            meta.append('<link rel="canonical" href="%s"/>' % esc(page_url))
            meta.append('<meta property="og:url" content="%s"/>' % esc(page_url))
        meta += ['<meta property="og:type" content="article"/>',
                 '<meta property="og:site_name" content="%s"/>' % CLINIC,
                 '<meta property="og:title" content="%s"/>' % esc(p["title"]),
                 '<meta property="og:description" content="%s"/>' % esc(p["excerpt"]),
                 '<meta property="article:published_time" content="%s"/>' % p["date"].isoformat(),
                 '<meta name="twitter:card" content="%s"/>' % ("summary_large_image" if og_img else "summary")]
        if og_img:
            meta.append('<meta property="og:image" content="%s"/>' % esc(og_img))
        ld = {"@context": "https://schema.org", "@type": "BlogPosting", "headline": p["title"],
              "description": p["excerpt"], "datePublished": p["date"].isoformat(),
              "author": {"@type": "Person", "name": p["author"]},
              "publisher": {"@type": "Organization", "name": CLINIC}}
        if og_img:
            ld["image"] = og_img
        if page_url:
            ld["mainEntityOfPage"] = page_url
        meta.append('<script type="application/ld+json">%s</script>' % json.dumps(ld, ensure_ascii=False).replace("</", "<\\/"))

        hero = ('<img src="%s" alt="%s" fetchpriority="high"/>' % (esc(p["image"]), esc(p["alt"]))) if p["image"] else ""
        values = {"SEO_META": "\n  ".join(meta), "HERO_IMG": hero, "CATEGORY": esc(p["category"]), "AUTHOR": esc(p["author"]),
                  "DATE_DISPLAY": esc(date_display(p["date"])), "BODY": render_body(p["body_md"]), "POST_NAV": nav,
                  "SIDEBAR_CATS": side, "TITLE": esc(p["title"])}
        page = re.sub(r"\{\{(\w+)\}\}", lambda m: values.get(m.group(1), m.group(0)), template)
        page = page.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n" + MARKER, 1)
        wrote += write_if_changed(ROOT / p["filename"], page)
    return wrote


def remove_stale_pages(live):
    keep = {p["filename"] for p in live}
    removed = []
    for f in ROOT.glob("blog-post-*.html"):
        if f.name in keep:
            continue
        try:
            head = f.read_text(encoding="utf-8")[:400]
        except Exception:
            continue
        if MARKER in head:           # only ever remove pages this builder made
            f.unlink()
            removed.append(f.name)
    return removed


def build_posts_json(live):
    items = []
    for p in live:
        items.append({"id": p["slug"], "title": p["title"], "category": p["category"], "author": p["author"],
                      "date": p["date"].isoformat(), "dateDisplay": date_display(p["date"]),
                      "day": p["date"].strftime("%d"), "month": p["date"].strftime("%b"),
                      "excerpt": p["excerpt"], "image": p["image"], "filename": p["filename"]})
    return write_if_changed(ROOT / "posts.json", json.dumps({"posts": items}, ensure_ascii=False, indent=2) + "\n")


def build_seo_files(live, site_url):
    wrote = 0
    if not site_url:
        return 0
    urls = [("", None), ("blog.html", None)]
    urls += [(f.name, None) for f in sorted(ROOT.glob("service-*.html"))]
    urls += [(p["filename"], p["date"].isoformat()) for p in live]
    xml = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for path, last in urls:
        loc = site_url + "/" + path if path else site_url + "/"
        xml.append("  <url><loc>%s</loc>%s</url>" % (esc(loc), ("<lastmod>%s</lastmod>" % last) if last else ""))
    xml.append("</urlset>")
    wrote += write_if_changed(ROOT / "sitemap.xml", "\n".join(xml) + "\n")
    robots = "User-agent: *\nAllow: /\nDisallow: /admin/\n\nSitemap: %s/sitemap.xml\n" % site_url
    wrote += write_if_changed(ROOT / "robots.txt", robots)
    return wrote


STATUS_CSS = """body{font-family:system-ui,-apple-system,'Segoe UI',Roboto,sans-serif;background:#F0F6FF;color:#0d1f2d;margin:0;line-height:1.6}
main{max-width:820px;margin:0 auto;padding:1.5rem 1rem 3rem}h1{font-size:1.5rem;margin:.2rem 0}h2{font-size:1.1rem;margin:2rem 0 .5rem;color:#183b56}
.card{background:#fff;border:1px solid #C5DDEF;border-radius:12px;padding:.9rem 1.1rem;margin:.5rem 0}.muted{color:#4f7396;font-size:.9rem}
.pill{display:inline-block;font-size:.75rem;padding:2px 10px;border-radius:20px;background:#E8F1FC;color:#183b56;margin-left:.4rem}
.bad{border-color:#f5b5b5;background:#fdecec}.note{border-color:#f0dca0;background:#fff8e1}a{color:#0b5ed7}"""


def build_status_page(posts, problems, site_url):
    live = [p for p in posts if p["status"] == "live"]
    sched = [p for p in posts if p["status"] == "scheduled"]
    drafts = [p for p in posts if p["status"] == "draft"]

    def card(p, extra=""):
        link = ('<a href="../%s">%s</a>' % (esc(p["filename"]), esc(p["title"]))) if p["status"] == "live" else esc(p["title"])
        return '<div class="card">%s<span class="pill">%s</span><div class="muted">%s &middot; %s</div>%s</div>' % (
            link, esc(p["category"]), esc(date_display(p["date"])), esc(p["source"]), extra)

    out = []
    out.append("<h2>Live on the website (%d)</h2>" % len(live))
    out += [card(p) for p in live] or ['<p class="muted">Nothing is live yet.</p>']
    out.append("<h2>Scheduled (%d)</h2>" % len(sched))
    out += [card(p, '<div class="muted">Will appear on the website on %s (checked every night).</div>' % esc(date_display(p["date"]))) for p in sched] \
        or ['<p class="muted">None.</p>']
    out.append("<h2>Drafts - hidden from the website (%d)</h2>" % len(drafts))
    out += [card(p, '<div class="muted">To publish: open it in the editor, switch on &ldquo;Show on website&rdquo;, and save.</div>') for p in drafts] \
        or ['<p class="muted">None.</p>']
    real = [x for x in problems if x.get("level") != "note"]
    notes = [x for x in problems if x.get("level") == "note"]
    out.append("<h2>Problems that stop an article showing (%d)</h2>" % len(real))
    out += ['<div class="card bad"><b>%s</b> &middot; %s<br>%s<br><span class="muted">What to do: %s</span></div>'
            % (esc(x["article"]), esc(x["field"]), esc(x["why"]), esc(x["fix"])) for x in real] \
        or ['<p class="muted">No problems found. &#10003;</p>']
    if notes:
        out.append("<h2>Worth fixing - the article still shows (%d)</h2>" % len(notes))
        out += ['<div class="card note"><b>%s</b> &middot; %s<br>%s<br><span class="muted">%s</span></div>'
                % (esc(x["article"]), esc(x["field"]), esc(x["why"]), esc(x["fix"])) for x in notes]

    page = """<!DOCTYPE html>
<html lang="en"><head><meta charset="UTF-8"/><meta name="viewport" content="width=device-width, initial-scale=1"/>
<meta name="robots" content="noindex,nofollow"/><title>Blog status - Elysian Dental Lounge</title>
<style>%s</style></head><body><main>
<p><a href="./">&larr; Back to the editor</a> &middot; <a href="guide.html">Help &amp; guide</a></p>
<h1>Blog status</h1>
<p class="muted">This page is made automatically. It shows what is live, what is waiting, and exactly why anything is not showing.
%s Last updated: <!--stamp-->%s<!--/stamp-->. Today is %s (clinic time).</p>
%s
</main></body></html>
""" % (STATUS_CSS, ("Website address: " + esc(site_url) + ".") if site_url else "", datetime.now(IST).strftime("%d %b %Y, %I:%M %p IST"),
       date_display(TODAY), "\n".join(out))
    # keep the 'last updated' time from changing the file when nothing else changed
    path = ROOT / "admin" / "status.html"
    if path.exists():
        old = path.read_text(encoding="utf-8")
        strip = lambda t: re.sub(r"<!--stamp-->.*?<!--/stamp-->", "", t, flags=re.S)
        if strip(old) == strip(page):
            return 0
    return write_if_changed(path, page)


# --------------------------------------------------------------------------- main
def main():
    if not TEMPLATE.exists():
        sys.exit("PROBLEM: the page template tools/post-template.html is missing, so no blog pages can be built. Restore that file from the repository history.")
    template = TEMPLATE.read_text(encoding="utf-8")
    problems = []
    posts = load_articles(problems)
    live = sorted([p for p in posts if p["status"] == "live"], key=lambda p: (p["date"], p["title"]), reverse=True)
    site_url = find_site_url()

    changed = build_pages(live, site_url, template)
    removed = remove_stale_pages(live)
    changed += build_posts_json(live)
    changed += build_seo_files(live, site_url)
    changed += build_status_page(posts, problems, site_url)

    print("Website address used: %s" % (site_url or "(none found - sitemap skipped)"))
    print("Articles: %d live, %d scheduled, %d draft" % (len(live), sum(p["status"] == "scheduled" for p in posts),
                                                         sum(p["status"] == "draft" for p in posts)))
    for r in removed:
        print("Removed page of an article that is no longer published: %s" % r)
    for x in problems:
        kind = "NOTE" if x.get("level") == "note" else "PROBLEM"
        print("%s in %s (%s): %s  ->  %s" % (kind, x["article"], x["field"], x["why"], x["fix"]))
        if os.environ.get("GITHUB_ACTIONS") and x.get("level") != "note":
            print("::warning title=Blog article problem::%s (%s): %s" % (x["article"], x["field"], x["why"]))
    print("%d file(s) written." % changed)


if __name__ == "__main__":
    main()
