def load_articles(problems):
    posts = []
    if not CONTENT.exists():
        return posts
    used_files = {}
    for f in sorted(CONTENT.glob("*.md")):
        name = f.name
        slug = f.stem

        def problem(field, why, fix):
            problems.append({"article": name, "field": field, "why": why, "fix": fix})

        fm_text, body = split_front_matter(f.read_text(encoding="utf-8"))
        if fm_text is None:
            problem("whole file", "The top part of the file (the details block between two '---' lines) is missing.",
                    "Open this article in the admin editor and save it again, or ask your web helper to restore it.")
            continue
        try:
            fm = yaml.safe_load(fm_text) or {}
            if not isinstance(fm, dict):
                raise ValueError("not a list of fields")
        except Exception as e:  # noqa: BLE001
            problem("whole file", "The details at the top of the article could not be read (%s)." % str(e).splitlines()[0],
                    "Open the article in the admin editor and save it again. If the editor cannot open it, a symbol such as a colon or quote in the title may need fixing.")
            continue

        title = str(fm.get("title") or "").strip()
        if len(title) < 3:
            problem("Title", "The article has no title.", "Open it in the editor and type a title.")
            continue

        d = parse_date(fm.get("date"))
        if not d:
            problem("Date", "The date is missing or not a real date (found: %r)." % (fm.get("date"),),
                    "Open the article in the editor and pick the date again.")
            continue

        text_body = (body or "").strip()
        if len(text_body) < 20:
            problem("Article text", "The article has no text (or almost none).", "Open it in the editor and write the article.")
            continue

        category = str(fm.get("category") or "").strip()
        if not category:
            problem("Category", "No category was chosen.", "Open the article and choose a category.")
            continue

        excerpt = re.sub(r"\s+", " ", str(fm.get("excerpt") or "")).strip()
        if not excerpt:
            problem("Short excerpt", "The short description shown on the blog list is empty.", "Open the article and write one or two sentences.")
            continue

        # draft / published switches (old files used 'draft')
        if "published" in fm:
            published = truthy(fm.get("published"))
        elif "draft" in fm:
            published = not truthy(fm.get("draft"))
        else:
            published = False
        status = "draft"
        if published:
            status = "live" if d <= TODAY else "scheduled"

        image = clean_image_path(fm.get("image"))
        if image and not re.match(r"^(https?:)?//", image):
            img_file = ROOT / image
            if not img_file.exists():
                problems.append({"article": name, "field": "Cover photo", "level": "note",
                                 "why": "The photo '%s' is not in the website files, so the article is shown without its cover photo." % image,
                                 "fix": "Open the article, choose the cover photo again (upload it), and save."})
                image = ""
            elif img_file.stat().st_size > BIG_IMAGE_BYTES:
                problems.append({"article": name, "field": "Cover photo", "level": "note",
                                 "why": "The cover photo is large (%d KB), which makes the page slower on mobile data." % (img_file.stat().st_size // 1024),
                                 "fix": "Upload a smaller version of the photo (under about 500 KB)."})

        if len(excerpt) > 180:
            problems.append({"article": name, "field": "Short excerpt", "level": "note",
                             "why": "The short excerpt is %d characters; over 180 may be cut off in search results." % len(excerpt),
                             "fix": "Shorten it to one or two sentences."})
        if category not in CATEGORIES:
            problems.append({"article": name, "field": "Category", "level": "note",
                             "why": "'%s' is not one of the usual categories, so it will not appear under a category button on the blog page." % category,
                             "fix": "Choose one of the categories offered in the editor."})

        raw_services = fm.get("services") or []
        if isinstance(raw_services, str):
            raw_services = [raw_services]
        services = []
        for sv in raw_services:
            key = str(sv).strip().lower()
            if key in SERVICES:
                if key not in services:
                    services.append(key)
            else:
                problems.append({"article": name, "field": "Related treatment", "level": "note",
                                 "why": "'%s' is not a treatment that has its own page, so it was ignored." % sv,
                                 "fix": "Open the article and choose the related treatment from the list offered."})

        filename = LEGACY_FILENAMES.get(slug, "blog-post-%s.html" % slug)
        if filename in used_files:
            problem("Title", "Another article already uses the same web address (%s)." % filename, "Change the title of one of them slightly.")
            continue
        used_files[filename] = name

        posts.append({
            "slug": slug, "source": name, "filename": filename, "title": title, "date": d, "category": category,
            "excerpt": excerpt, "image": image, "alt": str(fm.get("image_alt") or title).strip(),
            "author": str(fm.get("author") or "Dr. Yokesh Kumar R").strip(), "status": status, "body_md": text_body,
            "services": services,
        })
    return posts


