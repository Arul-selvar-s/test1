"""
Elysian Dental Lounge - blog builder
====================================

WHAT THIS DOES (in plain English)
  Reads the articles written in the admin editor (the files in content/blog/)
  and automatically creates:
    - one web page for every published article      (blog-post-<name>.html)
    - the list the blog page and homepage read from   (posts.json)
    - sitemap.xml and robots.txt for Google          (use the website address automatically)
    - admin/status.html, a page that tells the admin, in plain English,
      which articles are live, scheduled, drafts, or have a problem and why.

  It runs by itself on GitHub (see .github/workflows/build-blog.yml) every time
  an article is saved, and once every night so scheduled articles go live.
  Nobody has to run it by hand.

THE WEBSITE ADDRESS
  Nothing here is tied to one address. The address is found automatically:
    1. the SITE_URL setting, if one is given
    2. otherwise the file named CNAME (GitHub creates it when a custom domain
       is connected), so moving to a new domain needs no change at all
    3. otherwise the free github.io address of the repository.

To run it yourself (only needed for testing):   python3 tools/build_blog.py
Needs:  pip install markdown pyyaml
"""
