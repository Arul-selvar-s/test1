def esc(s):
    return html.escape(str(s), quote=True)


def write_if_changed(path, text):
    """Write a file only when its content really changed (keeps the history quiet)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    data = text.encode("utf-8")
    if path.exists() and path.read_bytes() == data:
        return False
    path.write_bytes(data)
    return True


def find_site_url():
    env = os.environ.get("SITE_URL", "").strip().rstrip("/")
    if env:
        return env
    cname = ROOT / "CNAME"
    if cname.exists():
        lines = [l.strip() for l in cname.read_text(encoding="utf-8").splitlines() if l.strip()]
        if lines:
            return "https://" + lines[0].replace("https://", "").replace("http://", "").rstrip("/")
    repo = os.environ.get("GITHUB_REPOSITORY", "")
    if "/" not in repo:
        try:
            remote = subprocess.check_output(["git", "-C", str(ROOT), "config", "--get", "remote.origin.url"],
                                             text=True, stderr=subprocess.DEVNULL).strip()
            m = re.search(r"github\.com[:/]+([^/]+)/([^/]+?)(?:\.git)?$", remote)
            if m:
                repo = m.group(1) + "/" + m.group(2)
        except Exception:
            pass
    if "/" in repo:
        owner, name = repo.split("/", 1)
        host = owner.lower() + ".github.io"
        return "https://" + host if name.lower() == host else "https://%s/%s" % (host, name)
    return ""


def parse_date(value):
    """Accepts 2026-04-08, 2026-04-08T10:30:00Z, or a real date. Returns a date in clinic time."""
    if isinstance(value, datetime):
        if value.tzinfo:
            value = value.astimezone(IST)
        return value.date()
    if isinstance(value, date):
        return value
    text = str(value or "").strip()
    if not text:
        return None
    if re.fullmatch(r"\d{4}-\d{2}-\d{2}", text):
        return date.fromisoformat(text)
    try:
        dt = datetime.fromisoformat(text.replace("Z", "+00:00"))
        if dt.tzinfo:
            dt = dt.astimezone(IST)
        return dt.date()
    except ValueError:
        return None


def truthy(v):
    if isinstance(v, bool):
        return v
    return str(v).strip().lower() in ("true", "yes", "1", "on")


def split_front_matter(raw):
    raw = raw.replace("\r\n", "\n").lstrip("﻿")
    m = re.match(r"---\n(.*?)\n---\n?(.*)\Z", raw, re.S)
    if not m:
        return None, raw
    return m.group(1), m.group(2)


CLEAN_TAGS = re.compile(r"<\s*(script|iframe|object|embed|style|form)\b.*?<\s*/\s*\1\s*>|<\s*(script|iframe|object|embed|style|form)\b[^>]*>",
                        re.I | re.S)
EVENT_ATTRS = re.compile(r"\s+on[a-z]+\s*=\s*(\"[^\"]*\"|'[^']*'|[^\s>]+)", re.I)


def render_body(md_text):
    body = markdown.markdown(md_text, extensions=["extra", "sane_lists"], output_format="html5")
    body = CLEAN_TAGS.sub("", body)           # safety: no scripts / embeds from article text
    body = EVENT_ATTRS.sub("", body)
    body = re.sub(r"javascript\s*:", "", body, flags=re.I)
    body = body.replace("<h1", "<h2").replace("</h1>", "</h2>")   # the page title is already the main heading
    # pictures added inside the article: make the path work from any address, load lazily
    body = re.sub(r'(src|href)="/(images/)', r'\1="\2', body)
    body = re.sub(r"<img (?![^>]*loading=)", '<img loading="lazy" ', body)
    return body


def clean_image_path(p):
    """Editor stores /images/blog/x.webp. Make it relative so it works on github.io/<repo>/ and on a custom domain."""
    p = str(p or "").strip()
    if not p or re.match(r"^(https?:)?//", p) or p.startswith("data:"):
        return p
    return p.lstrip("/")


def absolute(site_url, path):
    if not path or re.match(r"^(https?:)?//", path):
        return path
    return (site_url + "/" + path.lstrip("/")) if site_url else ""


